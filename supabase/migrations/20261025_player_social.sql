-- Addis Football: player social + chat foundation
create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'accepted' check (status in ('pending','accepted','blocked')),
  created_at timestamptz not null default now(),
  unique(requester_id, addressee_id),
  check (requester_id <> addressee_id)
);

create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  game_id bigint references public.games(id) on delete set null,
  kind text not null default 'friend' check (kind in ('friend','organizer')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (user_a <> user_b)
);
create unique index if not exists conversations_pair_game_unique
on public.conversations (least(user_a,user_b), greatest(user_a,user_b), coalesce(game_id,0));

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 3000),
  created_at timestamptz not null default now()
);
create index if not exists messages_conversation_created_idx on public.messages(conversation_id,created_at);

create table if not exists public.booking_players (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(booking_id,profile_id)
);

alter table public.friendships enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.booking_players enable row level security;

create policy "friendships visible to participants" on public.friendships for select using (auth.uid() in (requester_id,addressee_id));
create policy "users can add friendships" on public.friendships for insert with check (auth.uid() = requester_id);
create policy "participants can update friendships" on public.friendships for update using (auth.uid() in (requester_id,addressee_id));

create policy "conversations visible to participants" on public.conversations for select using (auth.uid() in (user_a,user_b));
create policy "participants can create conversations" on public.conversations for insert with check (auth.uid() in (user_a,user_b));
create policy "participants can update conversations" on public.conversations for update using (auth.uid() in (user_a,user_b));

create policy "messages visible to conversation participants" on public.messages for select using (exists(select 1 from public.conversations c where c.id=conversation_id and auth.uid() in (c.user_a,c.user_b)));
create policy "participants can send messages" on public.messages for insert with check (sender_id=auth.uid() and exists(select 1 from public.conversations c where c.id=conversation_id and auth.uid() in (c.user_a,c.user_b)));

create policy "booking owner can see selected players" on public.booking_players for select using (exists(select 1 from public.bookings b where b.id=booking_id and b.user_id=auth.uid()));
create policy "booking owner can add selected players" on public.booking_players for insert with check (exists(select 1 from public.bookings b where b.id=booking_id and b.user_id=auth.uid()));
create policy "booking owner can remove selected players" on public.booking_players for delete using (exists(select 1 from public.bookings b where b.id=booking_id and b.user_id=auth.uid()));

alter publication supabase_realtime add table public.messages;
